"""Wisp Phase 0: top-speed and flight-time estimates for the two Follow builds. Writes review/P0/speed.md.

Top speed, level flight at tilt angle theta:
    T(v) cos(theta) = W                (lift holds the weight)
    T(v) sin(theta) = D = 1/2 rho CdA v^2   (thrust's forward part balances drag)
  so the drone reaches speed v only while T(v) >= sqrt(W^2 + D(v)^2).
Prop thrust falls as the airflow approaches the prop's pitch speed (ESTIMATE, linear unloading):
    T(v) = T0 (1 - v / vp),   vp = 0.8 x KV x V x pitch / 60   (0.8: loaded rpm, ESTIMATE)
Flight time:  t = 0.8 x E_pack / (W / eta + P_electronics),   E_pack = capacity x nominal voltage
with eta the hover efficiency in grams of thrust per watt from a maker's thrust table (ESTIMATE when the table is for a proxy motor or prop) and 80 % of the
pack's energy treated as usable (ESTIMATE).
"""
import math
import pathlib

RHO = 1.20          # kg/m^3, sea level near San Pedro (ESTIMATE)
G = 9.81
P0 = pathlib.Path(__file__).resolve().parents[1]

BUILDS = [
    # name, mass kg, static thrust range g (4 motors), KV, cells, pitch in, CdA range m^2, basis
    ("Follow, 3 in ducted, 4S", 0.2415, (1400, 1800), 3850, 4, 1.75, (0.010, 0.020),
     "thrust ESTIMATE (no 1404 + 3 in ducted table found); pitch 1.75 in UNCONFIRMED"),
    ("Follow Fast, 3.5 in open, 6S", 0.2298, (2475, 2475), 2850, 6, 2.0, (0.005, 0.010),
     "thrust CLAIM: T-Motor P1604 2850KV table, 618.8 g x 4 on GF3520-3"),
    ("Follow Fast with guards, 6S 450", 0.2400, (2475, 2475), 2850, 6, 2.0, (0.010, 0.015),
     "guards add drag: CdA range ESTIMATE"),
]
FLIGHT = [
    # name, mass g, eta g/W at hover, capacity mAh, cells, electronics W
    ("Follow, 4S 550", 241.5, 3.5, 550, 4, 6.0, True),   # proxy: T-Motor P1604 3800KV, open GF3520-3
    ("Follow Fast, 6S 550", 229.8, 2.9, 550, 6, 4.0, False),
    ("Follow Fast with guards, 6S 450", 240.0, 2.9, 450, 6, 4.0, False),
]


def top_speed(m, T0_g, kv, cells, pitch_in, cda, volts_per_cell):
    W = m * G
    T0 = T0_g / 1000 * G
    vp = 0.8 * kv * cells * volts_per_cell * pitch_in * 0.0254 / 60
    lo, hi = 0.0, vp
    for _ in range(60):                       # bisection: largest v with T(v) >= sqrt(W^2 + D^2)
        v = (lo + hi) / 2
        T = T0 * (1 - v / vp)
        D = 0.5 * RHO * cda * v * v
        lo, hi = (v, hi) if T >= math.hypot(W, D) else (lo, v)
    D = 0.5 * RHO * cda * lo * lo
    return lo, vp, math.degrees(math.atan2(D, W))


def main():
    rows, lines = [], []
    for name, m, (t0a, t0b), kv, cells, pitch, (ca, cb), basis in BUILDS:
        res = []
        for t0 in sorted({t0a, t0b}):
            for cda in (ca, cb):
                for vpc in (3.7, 4.2):           # nominal and full charge, volts per cell
                    res.append(top_speed(m, t0, kv, cells, pitch, cda, vpc))
        vmin, vmax = min(r[0] for r in res), max(r[0] for r in res)
        tilt = (min(r[2] for r in res), max(r[2] for r in res))
        rows.append(f"| {name} | {m * 1000:.1f} g | {t0a if t0a == t0b else f'{t0a}-{t0b}'} g | {ca}-{cb} m² | "
                    f"{vmin:.0f}-{vmax:.0f} m/s | **{vmin * 3.6:.0f}-{vmax * 3.6:.0f} km/h** | **{vmin * 2.237:.0f}-{vmax * 2.237:.0f} mph** | {tilt[0]:.0f}-{tilt[1]:.0f}° | {basis} |")
    for name, m, eta, mah, cells, pe, proxy in FLIGHT:
        e = mah / 1000 * cells * 3.7
        p = m / eta + pe
        t = 0.8 * e / p * 60
        lines.append(f"| {name} | {m:.1f} g | {eta} g/W{' (proxy)' if proxy else ''} | {m:.1f} / {eta} + {pe} = {p:.0f} W | {mah} mAh × {cells} × 3.7 V = {e:.2f} Wh | **{t:.1f} min** |")
    md = f"""> STATUS: DRAFT - UNVERIFIED - requires human review at the Phase 0 gate

# How fast, how long (estimates)

Generated by `review/P0/calc/speed.py`. **No sub-250 g 3-3.5 inch quad with a GPS-logged top speed was found**
(research/follow-airframe.md, section 5), so these are physics estimates, not measurements. A two-way GPS-logged
pass at Phase 3 calibrates them.

## Top speed

Level flight at tilt θ: T(v)·cos θ = W and T(v)·sin θ = ½ρ·CdA·v², so the drone reaches v only while
T(v) ≥ √(W² + (½ρ·CdA·v²)²). Thrust falls as the air speed approaches the prop's pitch speed,
T(v) = T0·(1 − v/vp) with vp = 0.8 × KV × V × pitch / 60 (ESTIMATE). ρ = {RHO} kg/m³. The range covers both
ends of the thrust and drag-area (CdA) ranges and a pack at 3.7 V and 4.2 V per cell.

| Build | Mass | Static thrust T0 | CdA | Top speed (m/s) | (km/h) | (mph) | Tilt at top speed | Basis |
|---|---:|---:|---:|---:|---:|---:|---:|---|
{chr(10).join(rows)}

- **100 mph (161 km/h) is out of reach under 249.48 g** on these numbers. The limit is the prop's pitch speed, not
  drag: a light quad runs out of prop before it runs out of thrust, so 6S buys only about 10-15 % over 4S (two P1604
  setups compared in [`research/follow-airframe.md`](research/follow-airframe.md) §5.2).
- For comparison (maker claims): DJI Mini 5 Pro 18 m/s (65 km/h); the ducted GEPRC CineBot35 (583 g) is credited
  with 140-150 km/h.
- ArduPilot caps the lean angle (`ATC_ANGLE_MAX` in 4.7) and the speed in each mode (`WP_SPD`, `LOIT_SPEED_MS`).
  Reaching these speeds needs 60-75° of lean, so the Fast build needs a separate, higher-limit parameter set,
  used only in manual modes and never in follow-me.

## Flight time

t = 0.8 × E_pack / (W/η + P_electronics), with η the hover efficiency from a maker's thrust table at about 20 %
throttle. For the Follow build η is a proxy, ESTIMATE: the T-Motor P1604 3800KV on open GF3520-3 props
([`research/follow-airframe.md`](research/follow-airframe.md)), not the build's SPEEDX2 1404 in ducts, so its
flight time is an ESTIMATE too and 80 % of the pack usable (ESTIMATE). Electronics: about 6 W with the Pi and the O4, 4 W without the Pi
(ESTIMATE).

| Build | Mass | η | Power | Pack energy | Hover time |
|---|---:|---:|---|---|---:|
{chr(10).join(lines)}

**Plan on 5-7 minutes a pack**, about a quarter of a DJI Mini 5 Pro (36 min, maker claim). Two hours is not
possible for any multirotor under 249.48 g: at about 75 W, two hours needs 150 Wh, about 600 g of the best
lithium-ion cells at 250 Wh/kg.
"""
    (P0 / "speed.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
